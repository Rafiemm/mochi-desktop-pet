  // ---- walking -------------------------------------------------------------------------------------------
  const trap = (p, a) => (p < a ? (p * p) / (2 * a * (1 - a)) : p > 1 - a ? 1 - ((1 - p) * (1 - p)) / (2 * a * (1 - a)) : (p - a / 2) / (1 - a));
  function bounds() {
    const r = root.getBoundingClientRect(), m = 10;            // root itself never moves, only its walker child
    return { min: m - r.left, max: vw() - m - r.right, homeCenter: r.left + r.width / 2, w: r.width };
  }
  function targetOffset(target) {
    const b = bounds(); let cx;
    if (typeof target === "number") cx = target;
    else if (target === "home") return 0;
    else if (target === "left") return b.min;
    else if (target === "right") return Math.max(0, b.max);
    else if (target === "center") cx = vw() / 2;
    else {
      const el = typeof target === "string" ? document.querySelector(target) : target;
      if (!el || !el.getBoundingClientRect) return offsetX;
      const r = el.getBoundingClientRect(); cx = r.left + r.width / 2;
    }
    return clamp(cx - b.homeCenter, b.min, Math.max(b.min, b.max));
  }
  const setOffset = (x) => { offsetX = x; walker.style.transform = x ? "translate3d(" + x.toFixed(1) + "px,0,0)" : ""; };

  async function walkTo(target) {
    const tok = begin("walk");
    if (!ready || !rig) { end(tok); return false; }
    const dest = targetOffset(target), start = offsetX, dx = dest - start;
    if (Math.abs(dx) < 4) { end(tok); return true; }
    if (reduceMotion.matches) { setOffset(dest); layoutBubble(); end(tok); return true; }
    await warm(["walkA", "walkB"], []);
    if (!alive(tok)) return false;
    const u = unit(), cycle = ["walkA", "rest", "walkB", "rest"];
    let step = 0; look(cycle[0], "rest"); tailSpeed(1);          // real walk frames: A, stand, B, stand - plus a waddle sway and a bob
    const iv = setInterval(() => { step++; look(cycle[step % cycle.length], "rest"); }, STEP_MS);
    tok.stops.push(() => clearInterval(iv));
    play(tok, rockEl, [{ transform: "rotate(-2.2deg)" }, { transform: "rotate(2.2deg)" }], { duration: STEP_MS * 2, direction: "alternate", iterations: Infinity, easing: "ease-in-out" });
    play(tok, bounceEl, [{ transform: "translateY(0)" }, { transform: "translateY(" + (-0.012 * u) + "px)", offset: 0.5 }, { transform: "translateY(0)" }], { duration: STEP_MS * 2, iterations: Infinity, easing: "ease-in-out" });
    play(tok, rig.headAct, [{ transform: "rotate(1.6deg)" }, { transform: "rotate(-1.6deg)" }], { duration: STEP_MS * 2, direction: "alternate", iterations: Infinity, easing: "ease-in-out" });

    const ms = Math.max(800, Math.abs(dx) / (u * WALK_SPEED) * 1000);
    const arrived = await new Promise((resolve) => {
      const t0 = performance.now(); let id = 0;
      const frame = (now) => {
        if (tok.cancelled) return;
        const p = clamp((now - t0) / ms, 0, 1);
        setOffset(start + dx * trap(p, 0.16)); layoutBubble();
        if (p >= 1) resolve(true); else id = requestAnimationFrame(frame);
      };
      tok.stops.push(() => { cancelAnimationFrame(id); resolve(false); });
      id = requestAnimationFrame(frame);
    });
    if (!arrived || tok.cancelled) return false;
    tok.anims.forEach((a) => { try { a.cancel(); } catch (e) { /* ignore */ } }); tok.anims.length = 0;
    clearInterval(iv); look("rest", "rest");
    await play(tok, bounceEl, [{ transform: "scale(1,1)" }, { transform: "scale(1.04,.96)", offset: 0.4 }, { transform: "scale(1,1)" }], { duration: 260, easing: "ease-out" });
    return end(tok);
  }
  const home = () => walkTo("home");

  async function stroll() {
    if (!ready || reduceMotion.matches) return false;
    const b = bounds(), width = vw();
    let dest = rand(b.min, Math.max(b.min + 1, b.max)), tries = 0;
    while (Math.abs(dest - offsetX) < width * 0.22 && tries++ < 8) dest = rand(b.min, Math.max(b.min + 1, b.max));
    if (!(await walkTo(b.homeCenter + dest))) return false;
    await sleep(rand(1800, 3600));
    if (current) return false;                                 // something else took over while she was standing there
    const opts = ["wave", "jump", "thumbs", "dance", "wink"];
    if (Math.random() < 0.2 && !bubbleBusy) { say(nextPhrase() || "...", { duration: IDLE_HOLD }); await sleep(2600); } else await react(opts[(Math.random() * opts.length) | 0]);
    if (current) return false;
    await sleep(rand(800, 2200));
    if (current) return false;
    return walkTo("home");
  }
