  function hopFrames(h, s) {
    return [
      { transform: "translateY(0) scale(1,1)", offset: 0, easing: "ease-out" },
      { transform: "translateY(0) scale(" + (1 + 0.06 * s) + "," + (1 - 0.09 * s) + ")", offset: 0.18, easing: "cubic-bezier(.2,.7,.3,1)" },
      { transform: "translateY(" + (-h * 0.55) + "px) scale(" + (1 - 0.04 * s) + "," + (1 + 0.08 * s) + ")", offset: 0.38, easing: "ease-out" },
      { transform: "translateY(" + (-h) + "px) scale(1,1)", offset: 0.54, easing: "ease-in" },
      { transform: "translateY(" + (-h * 0.4) + "px) scale(" + (1 - 0.02 * s) + "," + (1 + 0.04 * s) + ")", offset: 0.76, easing: "ease-in" },
      { transform: "translateY(0) scale(" + (1 + 0.08 * s) + "," + (1 - 0.11 * s) + ")", offset: 0.88, easing: "ease-out" },
      { transform: "translateY(0) scale(1,1)", offset: 1 },
    ];
  }
  function shadowFrames(h) {
    const k = clamp(h / (unit() * 0.3), 0, 1);
    return [{ transform: "scale(1)", opacity: 1, offset: 0 }, { transform: "scale(1)", opacity: 1, offset: 0.18 }, { transform: "scale(" + (1 - 0.3 * k) + ")", opacity: 1 - 0.45 * k, offset: 0.54 }, { transform: "scale(1)", opacity: 1, offset: 0.88 }, { transform: "scale(1.06)", opacity: 1, offset: 0.9 }, { transform: "scale(1)", opacity: 1, offset: 1 }];
  }
  // one hop: crouch (stand frame), airborne frame while up, stand frame again on landing
  function hop(tok, h, ms, airPose, slot) {
    const t1 = setTimeout(() => { if (alive(tok)) look(airPose, slot); }, ms * 0.2), t2 = setTimeout(() => { if (alive(tok)) look("rest", slot); }, ms * 0.84);
    tok.stops.push(() => { clearTimeout(t1); clearTimeout(t2); });
    return Promise.all([play(tok, bounceEl, hopFrames(h, 1), { duration: ms }), play(tok, shadowEl, shadowFrames(h), { duration: ms })]).then((r) => r.every(Boolean));
  }

